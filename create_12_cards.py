def publish_all_12_cards():
    print(f"==================================================")
    print(f"🚀 Publishing 13 Cards to Category: '{CATEGORY_NAME}'")
    print(f"==================================================")
    
    now_ms = str(int(time.time() * 1000))
    success_count = 0

    for card in CARDS:
        doc_id = card["id"]
        title = card["title"]
        prompt = card["prompt"].strip()
        photo_text = card["photoText"].strip()
        order_num = card["num"]

        payload = {
            "fields": {
                "id": {"stringValue": doc_id},
                "title": {"stringValue": title},
                "category": {"stringValue": CATEGORY_NAME},
                "basePrompt": {"stringValue": prompt},
                "photoText": {"stringValue": photo_text},
                "caption": {"stringValue": card.get("caption", "").strip()},
                "order": {"integerValue": str(order_num)},
                "isNote": {"booleanValue": bool(card.get("isNote", False))},
                "createdAt": {"integerValue": now_ms},
                "updatedAt": {"integerValue": now_ms},
                "layers": {"arrayValue": {"values": []}}
            }
        }

        url = f"{FIRESTORE_CARDS_URL}/{doc_id}?key={FIREBASE_API_KEY}"
        data_bytes = json.dumps(payload).encode("utf-8")
        req = urllib.request.Request(
            url,
            data=data_bytes,
            headers={"Content-Type": "application/json"},
            method="PATCH"
        )

        try:
            with urllib.request.urlopen(req, timeout=15) as resp:
                print(f"✅ Card {order_num:02d}: '{title}' successfully saved!")
                success_count += 1
        except Exception as e:
            print(f"❌ Card {order_num:02d}: '{title}' FAILED! Error: {e}")

    print(f"\n🎉 Finished: {success_count}/{len(CARDS)} cards successfully pushed to Firestore!")

    # 2. Sync to Master Google Doc with rich visual color-coding
    try:
        from gdocs_service import send_to_google_docs, format_master_gdoc_content
        from push_video_and_poll_notes import POLLS_NOTE_CONTENT, VIDEO_NOTE_CONTENT
        print(f"\n==================================================")
        print(f"📄 Generating Master Google Doc via Webhook...")
        print(f"==================================================")
        gdoc_text = format_master_gdoc_content("14 September 2026", POLLS_NOTE_CONTENT, VIDEO_NOTE_CONTENT, CARDS)
        doc_url = send_to_google_docs("📅 14 Sep 2026 - अनुपमा संपूर्ण एपिसोड ड्राफ्ट", gdoc_text)
        if doc_url:
            print(f"✅ Master Google Doc successfully created: {doc_url}")
    except Exception as ge:
        print(f"Note: Google Doc sync error: {ge}")

    return success_count == len(CARDS)


if __name__ == "__main__":
    publish_all_12_cards()

