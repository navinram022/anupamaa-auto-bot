def sync_notes():
    # 1. Fetch current notes doc
    req = urllib.request.Request(NOTES_URL)
    try:
        with urllib.request.urlopen(req) as resp:
            data = json.loads(resp.read().decode('utf-8'))
    except Exception as e:
        print(f"Error fetching notes: {e}")
        data = {"fields": {}}

    fields = data.get("fields", {})
    existing_notes = []
    
    if "notes" in fields:
        raw_vals = fields["notes"].get("arrayValue", {}).get("values", [])
        for val in raw_vals:
            f = val.get("mapValue", {}).get("fields", {})
            existing_notes.append({
                "id": f.get("id", {}).get("stringValue", f"note_{int(time.time()*1000)}"),
                "title": f.get("title", {}).get("stringValue", "Untitled"),
                "content": f.get("content", {}).get("stringValue", ""),
                "createdAt": int(f.get("createdAt", {}).get("integerValue", time.time()*1000)),
                "updatedAt": int(f.get("updatedAt", {}).get("integerValue", time.time()*1000)),
            })

    # Generate fresh 12 viral ideas guaranteed not to repeat across 7 days
    try:
        from viral_ideas_tracker import build_decorated_viral_ideas_note
        from datetime import datetime
        today_str = datetime.now().strftime("%d %B %Y")
        dynamic_note_content, _ = build_decorated_viral_ideas_note(today_str)
    except Exception as e:
        print(f"Fallback to base note: {e}")
        dynamic_note_content = NOTE_CONTENT

    # Check if viral ideas note already exists
    target_id = "note_viral_post_ideas_beyond_12"
    found = False
    for n in existing_notes:
        if n["id"] == target_id or "12+ नए वायरल" in n["title"]:
            n["id"] = target_id
            n["title"] = "🔥 12+ नए वायरल पोस्ट आइडियाज"
            n["content"] = dynamic_note_content
            n["updatedAt"] = int(time.time() * 1000)
            found = True
            break

    if not found:
        existing_notes.append({
            "id": target_id,
            "title": "🔥 12+ नए वायरल पोस्ट आइडियाज",
            "content": dynamic_note_content,
            "createdAt": int(time.time() * 1000),
            "updatedAt": int(time.time() * 1000),
        })

    # Convert back to Firestore REST format
    firestore_notes_array = []
    for n in existing_notes:
        firestore_notes_array.append({
            "mapValue": {
                "fields": {
                    "id": {"stringValue": str(n["id"])},
                    "title": {"stringValue": str(n["title"])},
                    "content": {"stringValue": str(n["content"])},
                    "createdAt": {"integerValue": str(n.get("createdAt", int(time.time()*1000)))},
                    "updatedAt": {"integerValue": str(n.get("updatedAt", int(time.time()*1000)))},
                }
            }
        })

    payload = {
        "fields": {
            "notes": {
                "arrayValue": {
                    "values": firestore_notes_array
                }
            },
            "activeNoteId": {"stringValue": target_id},
            "updatedAt": {"integerValue": str(int(time.time() * 1000))},
        }
    }

    # If legacy text exists, keep it
    if "text" in fields:
        payload["fields"]["text"] = fields["text"]
    if "trashNotes" in fields:
        payload["fields"]["trashNotes"] = fields["trashNotes"]

    # PATCH to Firestore
    patch_url = f"{NOTES_URL}?updateMask.fieldPaths=notes&updateMask.fieldPaths=activeNoteId&updateMask.fieldPaths=updatedAt"
    req = urllib.request.Request(
        patch_url,
        data=json.dumps(payload).encode("utf-8"),
        headers={"Content-Type": "application/json"},
        method="PATCH"
    )

    try:
        with urllib.request.urlopen(req) as resp:
            print("Successfully synced Notes to Firestore app_meta/notes!")
            print(f"Total Notes Tabs: {len(existing_notes)}")
    except Exception as e:
        print(f"Error saving notes to Firestore: {e}")

